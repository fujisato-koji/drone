"""Record keys and the key tables of the flight over swell (Q-060).

python -m sim.wave_keys   rewrites the block of record/values.yaml between its two marker comments with one key
per result of the diagnosis of the earlier wave runs (sim/out/mpc.json key wave_diagnosis), of the wave library
(sim/out/mpc_library_wave.json) and of the closed-loop runs over swell (key wave_loop_exp, and wave_nav_exp when
it exists), and the key tables of docs/02-form.md#wave-loop between its wave_keys markers (the values show in the
generated value table of docs/01-requirements.md; the prose of the docs cites the keys, never the numbers).

Key names:
- wave.diag_<field>: the diagnosis (see diag_values).
- wave.lib_<aircraft>_<preset>_hs<H>_tp<T>_<field>: the library; fields soaring, motor, motor_near_zero (motor
  cycles below NEAR_ZERO_W of average power) and missing count the optimizer's slots (only where it ran),
  crest_seas the seas (wind and direction) with a soaring crest ride and crest_motor_seas those with only a motor
  crest ride, of seas seas.
- wave.sense_<phase|height>_<value>_<field> (sense_none: no error): the planner's sea known with an error, fields
  aloft_s, counted, power_after_w, motor_share and height_median_m (see the loop fields).
- wave.nav_<field>_<across|with>: the navigation runs over swell, by where the target lies relative to the
  swell's travel; the fields are those of sim.nav_keys (arrival_s is 0 when the run did not count).
- wave.loop_<field> (loop_summary): the counts, the power ratios against the flat sea and the motor shares of
  the closed-loop runs over swell.
- wave.loop_<aircraft>_hs<H>_<along|against|calm>_u<U>_<p63|p64>_<field>: the closed-loop runs, fields aloft_s,
  counted (1 when the run flew the whole time inside the band and the margins), power_w (average electric power
  over the run, W, the same number as the energy per hour in Wh/h), power_after_w (the same from the entry onto
  the wave library on), motor_share, height_median_m (above the local surface) and flat_power_w (the flat motor
  library's least power at the same wind).
"""
import json
import os

HERE = os.path.dirname(__file__)
ROOT = os.path.dirname(HERE)
MPC_JSON = os.path.join(HERE, "out", "mpc.json")
LIB_JSON = os.path.join(HERE, "out", "mpc_library_wave.json")
VALUES = os.path.join(ROOT, "record", "values.yaml")
DOC = os.path.join(ROOT, "docs", "02-form.md")
BEGIN = "  # generated by python -m sim.wave_keys: begin\n"
END = "  # generated by python -m sim.wave_keys: end\n"
SECTION = "docs/02-form.md#wave-loop"
SHORT = {"albatross-3m": "albatross", "baseline-2m": "baseline"}
PSHORT = {"p63": "p63", "p64_low": "p64"}
NEAR_ZERO_W = 0.5          # W; a motor cycle of the optimizer below this average power is counted as near zero
LOOP_FIELDS = (("aloft_s", "s"), ("counted", "1"), ("power_w", "W"), ("power_after_w", "W"), ("motor_share", "1"),
               ("height_median_m", "m"), ("flat_power_w", "W"))


def _num(v):
    """A number for a key name: 1.5 becomes 1p5 (a dot separates the parts of a key)."""
    return ("%g" % v).replace(".", "p").replace("-", "m")


def _key(k, v, unit):
    return ("  - key: %s\n    v: %s\n    unit: %s\n    status: calculated\n    basis:\n      - %s\n"
            % (k, v, unit, SECTION))


def _load():
    with open(MPC_JSON, encoding="utf-8") as fh:
        d = json.load(fh)
    lib = None
    if os.path.exists(LIB_JSON):
        with open(LIB_JSON, encoding="utf-8") as fh:
            lib = json.load(fh)
    return d, lib


def diag_values(d):
    """{field: (value, unit)} of the diagnosis."""
    rs = d["wave_diagnosis"]["results"]
    ws = [r for r in rs if r["kind"] == "wind_sea"]
    sw = [r for r in rs if r["kind"] == "swell"]
    flat_tip = [r for r in ws if r["planner_world"] == "flat" and r["ended"] == "tip contact"]
    crest = [r for r in ws if r["ended"] == "tip contact" and r["end"]["eta_over_std"] > 1.5]
    loops = [r for r in ws if abs(r["end"]["gamma_deg"]) > 180.0]
    truth = [r for r in ws if r["planner_world"] == "truth"]
    out = {"runs": (len(ws), "1"),
           "reproduced": (sum(abs(r["survival_s"] - r["recorded_survival_s"]) < 0.5 for r in ws), "1"),
           "flat_world_runs": (sum(r["planner_world"] == "flat" for r in ws), "1"),
           "crest_tip_runs": (len(crest), "1"),
           "crest_eta_std_min": (round(min(r["end"]["eta_over_std"] for r in crest), 2), "1"),
           "crest_eta_std_max": (round(max(r["end"]["eta_over_std"] for r in crest), 2), "1"),
           "flat_plan_tip_min_m": (round(min(r["plans_last5s"]["tip_world_min_m"] for r in flat_tip), 2), "m"),
           "flat_plan_tip_max_m": (round(max(r["plans_last5s"]["tip_world_min_m"] for r in flat_tip), 2), "m"),
           "flat_true_tip_min_m": (round(min(r["plans_last5s"]["tip_true_min_m"] for r in flat_tip), 2), "m"),
           "flat_true_tip_max_m": (round(max(r["plans_last5s"]["tip_true_min_m"] for r in flat_tip), 2), "m"),
           "looped_runs": (len(loops), "1"),
           "motor_share_min": (round(min(r["motor"]["thrust_on_share"] for r in ws), 2), "1"),
           "swell_runs": (len(sw), "1"),
           "swell_complete": (sum(r["ended"] == "complete" for r in sw), "1"),
           "swell_motor_share_min": (round(min(r["motor"]["thrust_on_share"] for r in sw), 2), "1"),
           "swell_power_min_w": (round(min(r["motor"]["avg_power_w"] for r in sw), 1), "W"),
           "swell_power_max_w": (round(max(r["motor"]["avg_power_w"] for r in sw), 1), "W"),
           "swell_h_median_min_m": (round(min(r["h_median_m"] for r in sw), 1), "m"),
           "swell_h_median_max_m": (round(max(r["h_median_m"] for r in sw), 1), "m"),
           "swell_h_min_m": (round(min(r["h_min_m"] for r in sw), 2), "m")}
    if truth:
        t = truth[0]
        out["truth_plan_tip_m"] = (round(t["plans_last5s"]["tip_world_min_m"], 2), "m")
        out["truth_true_tip_m"] = (round(t["plans_last5s"]["tip_true_min_m"], 2), "m")
        out["truth_dead_mean"] = (round(t["plans_last5s"]["n_dead_mean"], 0), "1")
    return out


def lib_groups(lib):
    """{(aircraft, preset, hs, tp): {field: count}}."""
    g = {}
    for e in lib["entries"]:
        k = (e["aircraft"], e["preset"], e["hs"], e["tp"])
        c = g.setdefault(k, {"soaring": 0, "motor": 0, "motor_near_zero": 0, "missing": 0, "_crest": set(),
                             "_crest_motor": set()})
        sea = (e["direction"], e["u10"])
        if e.get("crest"):
            (c["_crest"] if e["kind"] == "soaring" else c["_crest_motor"]).add(sea)
        elif not e.get("success"):
            c["missing"] += 1
        else:
            c[e["kind"]] += 1
            if e["kind"] == "motor" and e["power_avg_w"] < NEAR_ZERO_W:
                c["motor_near_zero"] += 1
    from sim.wavelib import wave_seas
    for (a, p, hs, tp), c in g.items():
        c["seas"] = len(wave_seas(hs, tp))
        c["crest_seas"] = len(c.pop("_crest"))
        c["crest_motor_seas"] = len(c.pop("_crest_motor"))
    return g


def lib_values(lib):
    out = {}
    dsopt_seas = {(e["aircraft"], e["preset"], e["hs"], e["tp"]) for e in lib["entries"] if not e.get("crest")}
    for (a, p, hs, tp), c in sorted(lib_groups(lib).items()):
        base = "lib_%s_%s_hs%s_tp%g_" % (SHORT[a], PSHORT[p], _num(hs), tp)
        fields = ("crest_seas", "crest_motor_seas", "seas")
        if (a, p, hs, tp) in dsopt_seas:
            fields = ("soaring", "motor", "motor_near_zero", "missing") + fields
        for f in fields:
            out[base + f] = (c[f], "1")
    return out


def case_id(r):
    d = "calm" if r["u10"] == 0.0 else r["direction"]
    return "loop_%s_hs%s_%s_u%g_%s" % (SHORT[r["aircraft"]], _num(r["hs"]), d, r["u10"], PSHORT[r["preset"]])


def loop_values(rows):
    out = {}
    for r in rows:
        a = r.get("after_entry") or {}
        v = {"aloft_s": round(r["survival_s"], 0), "counted": int(r["margins"]["counts"]),
             "power_w": round(r["motor"]["avg_power_w"], 1),
             "power_after_w": round(a["avg_power_w"], 1) if a else None,
             "motor_share": round(r["motor"]["thrust_on_share"], 2),
             "height_median_m": round(r["margins"]["height_median_m"], 1),
             "flat_power_w": round(r["flat"]["power_avg_w"], 1) if r.get("flat") else None}
        for f, u in LOOP_FIELDS:
            if v[f] is not None:
                out["%s_%s" % (case_id(r), f)] = (v[f], u)
    return out


def loop_summary(rows):
    """Summary keys of the closed-loop runs over swell."""
    full = [r for r in rows if r["ended"] == "complete"]
    cnt = [r for r in rows if r["margins"]["counts"]]
    ent = [r for r in rows if (r.get("entry") or {}).get("kind")]
    flat_only = [r for r in rows if not (r.get("entry") or {}).get("kind")]
    rat = sorted((r["after_entry"]["avg_power_w"] / r["flat"]["power_avg_w"]) for r in cnt
                 if r.get("after_entry") and r.get("flat") and r["flat"]["power_avg_w"] > 0)
    share = sorted(r["motor"]["thrust_on_share"] for r in cnt)
    pw = sorted(r["after_entry"]["avg_power_w"] for r in cnt if r.get("after_entry"))
    low = [r for r in cnt if r["motor"]["thrust_on_share"] <= 0.1]
    out = {"loop_runs": (len(rows), "1"), "loop_full": (len(full), "1"), "loop_counted": (len(cnt), "1"),
           "loop_counted_p63": (sum(r["preset"] == "p63" for r in cnt), "1"),
           "loop_counted_p64": (sum(r["preset"] == "p64_low" for r in cnt), "1"),
           "loop_flat_only": (len(flat_only), "1"),
           "loop_flat_only_ended": (sum(r["ended"] != "complete" for r in flat_only), "1"),
           "loop_ended_early": (len(rows) - len(full), "1"),
           "loop_ratio_min": (round(rat[0], 3), "1"), "loop_ratio_median": (round(rat[len(rat) // 2], 2), "1"),
           "loop_ratio_max": (round(rat[-1], 2), "1"),
           "loop_power_min_w": (round(pw[0], 1), "W"), "loop_power_median_w": (round(pw[len(pw) // 2], 1), "W"),
           "loop_motor_share_min": (round(share[0], 3), "1"),
           "loop_motor_share_median": (round(share[len(share) // 2], 2), "1"),
           "loop_low_motor_runs": (len(low), "1"),
           "loop_u3_power_max_w": (round(max(r["motor"]["avg_power_w"] for r in rows if r["u10"] == 3.0), 1), "W")}
    return out


def sense_id(r):
    e = r.get("planner_sea_error")
    if e is None:
        return "sense_none"
    return "sense_%s_%s" % (e[0], _num(e[1]))


def sense_values(rows):
    out = {}
    for r in rows:
        a = r.get("after_entry") or {}
        v = {"aloft_s": (round(r["survival_s"], 0), "s"), "counted": (int(r["margins"]["counts"]), "1"),
             "power_after_w": (round(a["avg_power_w"], 1), "W") if a else None,
             "motor_share": (round(r["motor"]["thrust_on_share"], 2), "1"),
             "height_median_m": (round(r["margins"]["height_median_m"], 1), "m")}
        for f, vu in v.items():
            if vu is not None:
                out["%s_%s" % (sense_id(r), f)] = vu
    return out


def nav_values_all(rows):
    out = {}
    for r in rows:
        for k, v in nav_values(r).items():
            out["%s_%s" % (k, r["target_rel_swell"])] = v
    return out


def nav_values(r):
    nv, m, p = r.get("nav") or {}, r["motor"], r["predicted"]
    counted = bool(nv.get("counts_as_arrived"))
    return {"nav_arrival_s": (round(nv["arrival_time_s"], 0) if counted else 0, "s"), "nav_counted": (int(counted), "1"),
            "nav_vmg_ms": (round(nv["mean_vmg_ms"], 2), "m/s"), "nav_hull_ms": (round(p["plan_vmg_ms"], 2), "m/s"),
            "nav_hull_s": (round(p["time_s"], 0), "s"), "nav_energy_wh": (round(m["energy_wh"], 1), "Wh"),
            "nav_motor_share": (round(m["thrust_on_share"], 2), "1"),
            "nav_height_median_m": (round(nv["height_median_m"], 1), "m"),
            "nav_height_min_m": (round(nv["height_min_m"], 1), "m"), "nav_height_max_m": (round(nv["height_max_m"], 1), "m"),
            "nav_hull_points": (int(r["hull_points"]), "1")}


def values_block():
    d, lib = _load()
    parts = [{"diag_" + k: v for k, v in diag_values(d).items()}]
    if lib is not None:
        parts.append(lib_values(lib))
    if "wave_loop_exp" in d:
        parts.append(loop_values(d["wave_loop_exp"]["results"]))
        parts.append(loop_summary(d["wave_loop_exp"]["results"]))
    if "wave_sense_exp" in d:
        parts.append(sense_values(d["wave_sense_exp"]["results"]))
    if "wave_nav_exp" in d:
        parts.append(nav_values_all(d["wave_nav_exp"]["results"]))
    out = [BEGIN]
    for p in parts:
        for k, (v, u) in p.items():
            out.append(_key("wave." + k, v, u))
    out.append(END)
    return "".join(out)


def loop_table(rows):
    lines = ["| aircraft | Hs | swell | u10 | wave wind | " + " | ".join(f.replace("_", " ") for f, _ in LOOP_FIELDS)
             + " |", "|" + "---|" * (5 + len(LOOP_FIELDS))]
    for r in rows:
        cid = case_id(r)
        lines.append("| %s | %g | %s | %g | %s | " % (SHORT[r["aircraft"]], r["hs"],
                                                       "calm" if r["u10"] == 0.0 else r["direction"], r["u10"],
                                                       PSHORT[r["preset"]])
                     + " | ".join("wave.%s_%s" % (cid, f) for f, _ in LOOP_FIELDS) + " |")
    return chr(10).join(lines) + chr(10)


def lib_table(lib):
    lines = ["| aircraft | wave wind | Hs | Tp | optimizer: soaring, motor (of them near zero power), missing slots | seas with a soaring crest "
             "ride, with a motor crest ride only, of |", "|---|---|---|---|---|---|"]
    vals = lib_values(lib)
    for (a, p, hs, tp) in sorted(lib_groups(lib)):
        base = "wave.lib_%s_%s_hs%s_tp%g_" % (SHORT[a], PSHORT[p], _num(hs), tp)
        opt = (", ".join(base + f for f in ("soaring", "motor", "motor_near_zero", "missing"))
               if (base[5:] + "soaring") in vals else "not solved")
        lines.append("| %s | %s | %g | %g | %s | %s |" % (SHORT[a], PSHORT[p], hs, tp, opt,
                                                           ", ".join(base + f for f in ("crest_seas", "crest_motor_seas",
                                                                                         "seas"))))
    return chr(10).join(lines) + chr(10)


def sense_table(rows):
    fields = ("aloft_s", "counted", "power_after_w", "motor_share", "height_median_m")
    lines = ["| planner's sea | " + " | ".join(f.replace("_", " ") for f in fields) + " |",
             "|" + "---|" * (1 + len(fields))]
    for r in rows:
        e = r.get("planner_sea_error")
        name = "as it is" if e is None else ("phase %+g rad" % e[1] if e[0] == "phase" else "height x %g" % e[1])
        cid = sense_id(r)
        lines.append("| %s | " % name + " | ".join("wave.%s_%s" % (cid, f) for f in fields) + " |")
    return chr(10).join(lines) + chr(10)


def nav_table(rows):
    fields = ("arrival_s", "counted", "vmg_ms", "hull_ms", "hull_s", "energy_wh", "motor_share", "height_median_m",
              "height_min_m", "height_max_m", "hull_points")
    lines = ["| target | " + " | ".join(f.replace("_", " ") for f in fields) + " |",
             "|" + "---|" * (1 + len(fields))]
    for r in rows:
        lines.append("| %s the swell | " % r["target_rel_swell"]
                     + " | ".join("wave.nav_%s_%s" % (f, r["target_rel_swell"]) for f in fields) + " |")
    return chr(10).join(lines) + chr(10)


def _replace(text, tag, body):
    b, e = "<!-- %s begin -->" % tag + chr(10), "<!-- %s end -->" % tag
    if b not in text:
        return text
    i, j = text.index(b) + len(b), text.index(e)
    return text[:i] + body + text[j:]


def main():
    with open(VALUES, encoding="utf-8", newline="") as fh:
        s = fh.read()
    blk = values_block()
    if BEGIN not in s:
        raise SystemExit("add the two marker comment lines to record/values.yaml first")
    i, j = s.index(BEGIN), s.index(END) + len(END)
    s = s[:i] + blk + s[j:]
    with open(VALUES, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(s)
    d, lib = _load()
    with open(DOC, encoding="utf-8", newline="") as fh:
        t = fh.read()
    if lib is not None:
        t = _replace(t, "wave_lib_keys", lib_table(lib))
    if "wave_loop_exp" in d:
        t = _replace(t, "wave_loop_keys", loop_table(d["wave_loop_exp"]["results"]))
    if "wave_sense_exp" in d:
        t = _replace(t, "wave_sense_keys", sense_table(d["wave_sense_exp"]["results"]))
    if "wave_nav_exp" in d:
        t = _replace(t, "wave_nav_keys", nav_table(d["wave_nav_exp"]["results"]))
    with open(DOC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(t)


if __name__ == "__main__":
    main()
