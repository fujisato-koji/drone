"""Record keys and the key table of the navigation experiments.

python -m sim.nav_keys   rewrites the block of record/values.yaml between the two marker comments with one
key per result of the runs `nav_exp` (5 km) and `nav_exp_10km` in sim/out/mpc.json, and the key table of
docs/02-form.md#navigation between its nav_keys markers (the values show in the generated value table of
docs/01-requirements.md; the prose of the docs cites the keys, never the numbers).

Key names: nav.<run>_<aircraft>_u<wind>_<direction>_<field> with run "run5" or "run10", aircraft
"albatross" / "baseline", fields: arrival_s (0 when the run did not count as arrived), counted (1 when it
arrived inside the height band and the margins), vmg_ms, hull_ms (speed made good of the hull plan), hull_s
(kinematic arrival time), energy_wh, motor_share, height_median_m, height_max_m.
"""
import json
import os
import re

HERE = os.path.dirname(__file__)
ROOT = os.path.dirname(HERE)
MPC_JSON = os.path.join(HERE, "out", "mpc.json")
VALUES = os.path.join(ROOT, "record", "values.yaml")
DOC = os.path.join(ROOT, "docs", "02-form.md")
BEGIN = "  # generated by python -m sim.nav_keys: begin\n"
END = "  # generated by python -m sim.nav_keys: end\n"
FIELDS = (("arrival_s", "s"), ("counted", "1"), ("vmg_ms", "m/s"), ("hull_ms", "m/s"), ("hull_s", "s"),
          ("energy_wh", "Wh"), ("motor_share", "1"), ("height_median_m", "m"), ("height_max_m", "m"))
SHORT = {"albatross-3m": "albatross", "baseline-2m": "baseline"}


def case_id(run, r):
    return "%s_%s_u%g_%s" % (run, SHORT.get(r["aircraft"], r["aircraft"].split("-")[0]), r["u10"], r["direction"])


def case_values(r):
    nv, m, p = r["nav"], r["motor"], r["predicted"]
    counted = bool(nv.get("counts_as_arrived"))
    return {"arrival_s": round(nv["arrival_time_s"], 0) if counted else 0, "counted": int(counted),
            "vmg_ms": round(nv["mean_vmg_ms"], 2), "hull_ms": round(p["plan_vmg_ms"], 2),
            "hull_s": round(p["time_s"], 0), "energy_wh": round(m["energy_wh"], 1),
            "motor_share": round(m["thrust_on_share"], 2), "height_median_m": round(nv["height_median_m"], 1),
            "height_max_m": round(nv["height_max_m"], 1)}


def runs():
    with open(MPC_JSON, encoding="utf-8") as fh:
        d = json.load(fh)
    return [("run5", d["nav_exp"]["results"]), ("run10", d["nav_exp_10km"]["results"])]


def values_block():
    out = [BEGIN]
    for run, rows in runs():
        for r in rows:
            cid = case_id(run, r)
            for f, u in FIELDS:
                v = case_values(r)[f]
                out.append("  - key: nav.%s_%s\n    v: %s\n    unit: %s\n    status: calculated\n    basis:\n"
                           "      - docs/02-form.md#navigation\n" % (cid, f, v, u))
    out.append(END)
    return "".join(out)


def table_text():
    lines = ["| aircraft | u10 | target | arrival time | counted | VMG | hull speed | hull time | energy | motor on | "
             "height median | height max |", "|" + "---|" * 12]
    for run, rows in runs():
        for r in rows:
            cid = case_id(run, r)
            lines.append("| %s | %g | %s %g km | " % (SHORT.get(r["aircraft"], r["aircraft"]), r["u10"], r["direction"],
                                                      r["distance_m"] / 1000.0)
                         + " | ".join("nav.%s_%s" % (cid, f) for f, _ in FIELDS) + " |")
    return "\n".join(lines) + "\n"


def main():
    with open(VALUES, encoding="utf-8", newline="") as fh:
        s = fh.read()
    blk = values_block()
    if BEGIN in s:
        i, j = s.index(BEGIN), s.index(END) + len(END)
        s = s[:i] + blk + s[j:]
    else:
        raise SystemExit("add the two marker comment lines to record/values.yaml first")
    with open(VALUES, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(s)
    with open(DOC, encoding="utf-8", newline="") as fh:
        t = fh.read()
    b, e = "<!-- nav_keys begin -->" + chr(10), "<!-- nav_keys end -->"
    i, j = t.index(b) + len(b), t.index(e)
    t = t[:i] + table_text() + t[j:]
    with open(DOC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(t)


if __name__ == "__main__":
    main()
