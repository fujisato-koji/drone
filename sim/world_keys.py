"""Record keys and key tables of the world map and the world sea (docs/02-form.md#world-map).

python -m sim.world_keys   rewrites the block of record/values.yaml between its two marker comments with the keys
below, read from sim/world.py and the files in sim/viewer/world, and the key tables of docs/02-form.md#world-map
between their world_keys markers (the prose cites the keys, never the numbers).

- the grids, frames, quantization steps and pace of sim/world.py: assumed, open item OPEN_ITEM (the owner's data
  budget of 2026-11-01, not yet a decision);
- world.corridor_{length,width}_km, world.global_ocean_points, world.{global,corridor}_bytes (one byte per value),
  world.calls_{corridor,global} (calls of the free API for one fetch), world.land_{bytes,points},
  world.scenario_file_max_bytes, world.index_bytes: calculated;
- per scenario s: world.<s>_{u10_mean,u10_max}_ms, world.<s>_{hs_mean,hs_max,swell_mean}_m, world.<s>_tp_mean_s,
  world.<s>_clipped (values outside the byte range) over all points and frames of its corridor: calculated.
"""
import os

import numpy as np

from sim import world as W

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VALUES = os.path.join(ROOT, "record", "values.yaml")
DOC = os.path.join(ROOT, "docs", "02-form.md")
BEGIN = "  # generated by python -m sim.world_keys: begin\n"
END = "  # generated by python -m sim.world_keys: end\n"
BASIS = "docs/02-form.md#world-map"
OPEN_ITEM = "Q-078"


def _num(x, nd):
    x = round(float(x), nd)
    return int(x) if nd <= 0 or x == int(x) else x


def keys():
    """(key, value, unit, status) in a fixed order."""
    a = "assumed"
    out = [("world.global_step_deg", W.GLOBAL["step_deg"], "deg", a),
           ("world.global_lat_max_deg", W.GLOBAL["lat0"] + W.GLOBAL["step_deg"] * (W.GLOBAL["nlat"] - 1), "deg", a),
           ("world.corridor_step_km", W.CORRIDOR["step_km"], "km", a),
           ("world.corridor_points_along", W.CORRIDOR["na"], "1", a),
           ("world.corridor_points_across", W.CORRIDOR["nc"], "1", a),
           ("world.frame_step_h", W.FRAMES["dt_h"], "h", a),
           ("world.frames", W.FRAMES["nt"], "1", a),
           ("world.q_wind_ms", W.QUANT["u10"]["step"], "m/s", a),
           ("world.q_height_m", W.QUANT["hs"]["step"], "m", a),
           ("world.q_period_s", W.QUANT["tsw"]["step"], "s", a),
           ("world.q_dir_deg", _num(W.QUANT["dsw"]["step"], 3), "deg", a),
           ("world.pace_calls_per_min", W.LIMITS["minute"], "1/min", a),
           ("world.pace_calls_per_h", W.LIMITS["hour"], "1/h", a),
           ("world.pace_calls_per_day", W.LIMITS["day"], "1/d", a)]
    c = "calculated"
    n_ocean = int(W.ocean_mask(W.load_land()).sum())
    npnt = W.CORRIDOR["na"] * W.CORRIDOR["nc"]
    out += [("world.corridor_length_km", _num((W.CORRIDOR["na"] - 1) * W.CORRIDOR["step_km"], 1), "km", c),
            ("world.corridor_width_km", _num((W.CORRIDOR["nc"] - 1) * W.CORRIDOR["step_km"], 1), "km", c),
            ("world.global_ocean_points", n_ocean, "1", c),
            ("world.global_bytes", len(W.GLOBAL_VARS) * n_ocean, "B", c),
            ("world.corridor_bytes", W.FRAMES["nt"] * len(W.CORRIDOR_VARS) * npnt, "B", c),
            ("world.calls_corridor", 2 * npnt, "1", c),
            ("world.calls_global", 2 * n_ocean, "1", c)]
    land = W.LAND_JS
    rings = W.load_land()
    out += [("world.land_bytes", os.path.getsize(land), "B", c), ("world.land_points", sum(len(r) for r in rings), "1", c)]
    sizes = []
    for s in W.SCENARIOS:
        p = W.OUT_DIR / f"{s['id']}.js"
        if not p.exists():
            continue
        sizes.append(p.stat().st_size)
        d = W.load_js(p)
        f = W.unpack_field(d["corridor"])
        v = f["vals"]
        sp = np.hypot(v["u10"], v["v10"])
        i = s["id"]
        out += [(f"world.{i}_u10_mean_ms", _num(np.nanmean(sp), 1), "m/s", c),
                (f"world.{i}_u10_max_ms", _num(np.nanmax(sp), 1), "m/s", c),
                (f"world.{i}_hs_mean_m", _num(np.nanmean(v["hs"]), 2), "m", c),
                (f"world.{i}_hs_max_m", _num(np.nanmax(v["hs"]), 2), "m", c),
                (f"world.{i}_swell_mean_m", _num(np.nanmean(v["hsw"]), 2), "m", c),
                (f"world.{i}_tp_mean_s", _num(np.nanmean(v["tsw"]), 1), "s", c),
                (f"world.{i}_clipped", sum(d["corridor"]["clipped"].values()) + sum(d["global"]["clipped"].values()), "1", c)]
    if sizes:
        out.append(("world.scenario_file_max_bytes", max(sizes), "B", c))
    if (W.OUT_DIR / "index.js").exists():
        out.append(("world.index_bytes", (W.OUT_DIR / "index.js").stat().st_size, "B", c))
    return out


def values_block(ks):
    lines = [BEGIN]
    for k, v, u, st in ks:
        basis = OPEN_ITEM if st == "assumed" else BASIS
        lines.append(f"  - key: {k}\n    v: {v}\n    unit: {u}\n    status: {st}\n    basis:\n      - {basis}\n")
    lines.append(END)
    return "".join(lines)


def _row(cells):
    return "| " + " | ".join(str(x) for x in cells) + " |"


def table_scenarios(ks):
    have = {k for k, *_ in ks}
    head = ["case", "start (UTC)", "centre", "mean wind", "largest wind", "mean height", "largest height",
            "mean swell", "mean swell period"]
    L = [_row(head), "|" + "---|" * len(head)]
    for s in W.SCENARIOS:
        i = s["id"]
        if f"world.{i}_u10_mean_ms" not in have:
            continue
        lat, lon = s["lat"], s["lon"]
        centre = f"{abs(lat):g} {'N' if lat >= 0 else 'S'} {abs(lon):g} {'E' if lon >= 0 else 'W'}"
        L.append(_row([s["title"]["en"], s["start"], centre] + [f"world.{i}_{x}" for x in
                       ("u10_mean_ms", "u10_max_ms", "hs_mean_m", "hs_max_m", "swell_mean_m", "tp_mean_s")]))
    return L


def table_budget(ks):
    L = [_row(["item", "key"]), "|---|---|"]
    rows = [("global snapshot: grid step, highest latitude", "world.global_step_deg, world.global_lat_max_deg"),
            ("global snapshot: ocean points, bytes of data", "world.global_ocean_points, world.global_bytes"),
            ("corridor: step, points along and across", "world.corridor_step_km, world.corridor_points_along, world.corridor_points_across"),
            ("corridor: length and width", "world.corridor_length_km, world.corridor_width_km"),
            ("corridor: frame step, frames, bytes of data", "world.frame_step_h, world.frames, world.corridor_bytes"),
            ("one byte per value: wind, height, period, direction", "world.q_wind_ms, world.q_height_m, world.q_period_s, world.q_dir_deg"),
            ("largest scenario file, index file", "world.scenario_file_max_bytes, world.index_bytes"),
            ("land file and its points", "world.land_bytes, world.land_points"),
            ("free API calls for one corridor, one global snapshot", "world.calls_corridor, world.calls_global"),
            ("pace kept by the fetcher (minute, hour, UTC day)", "world.pace_calls_per_min, world.pace_calls_per_h, world.pace_calls_per_day")]
    for a, b in rows:
        L.append(_row([a, b]))
    return L


TABLES = {"scenarios": table_scenarios, "budget": table_budget}


def main():
    ks = keys()
    with open(VALUES, encoding="utf-8", newline="") as fh:
        s = fh.read()
    if BEGIN in s:
        i, j = s.index(BEGIN), s.index(END) + len(END)
        s = s[:i] + values_block(ks) + s[j:]
    else:
        s = s.rstrip("\n") + "\n" + values_block(ks)
    with open(VALUES, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(s)
    with open(DOC, encoding="utf-8", newline="") as fh:
        t = fh.read()
    for name, fn in TABLES.items():
        b, e = f"<!-- world_keys {name} begin -->\n", f"<!-- world_keys {name} end -->"
        if b not in t:
            raise SystemExit(f"add the markers of the {name} table to docs/02-form.md first")
        i, j = t.index(b) + len(b), t.index(e)
        t = t[:i] + "\n".join(fn(ks)) + "\n" + t[j:]
    with open(DOC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(t)
    print(f"wrote {len(ks)} keys")


if __name__ == "__main__":
    main()
