def values_block(d):
    parts = []
    if "wave_pilot_exp" in d:
        rows = d["wave_pilot_exp"]["results"]
        trials = d.get("wave_pilot_trials", {}).get("results", [])
        parts.append((pilot_values(rows, trials), SEC_WAVE, "wave."))
        parts.append((pilot_summary(rows, d["wave_loop_exp"]["results"], trials), SEC_WAVE, "wave."))
    if "wave_leg_exp" in d:
        parts.append((leg_values(leg_rows(d)), SEC_WAVE, "wave."))
    if "reflex_exp" in d:
        parts.append((reflex_values(d["reflex_exp"]["summary"]), SEC_REFLEX, "reflex."))
    for k0, kr in (("nav_exp", "nav_exp_reflex2"), ("nav_exp_10km", "nav_exp_10km_reflex2")):
        if kr in d:
            parts.append((reflex_nav_values(d[kr]["results"], d[k0]["results"], d[kr]["meta"]["distance_m"]),
                          SEC_REFLEX, "reflex."))
    if "wave_pilot_reflex_exp" in d and "wave_pilot_exp" in d:
        parts.append((reflex_loop_values(d["wave_pilot_reflex_exp"]["results"], d["wave_pilot_exp"]["results"]),
                      SEC_REFLEX, "reflex."))
    out = [BEGIN]
    for vals, sec, pre in parts:
        for k, (v, u) in vals.items():
            out.append(_key(pre + k, v, u, sec))
    out.append(END)
    return "".join(out)


def _replace(text, tag, body):
    b, e = "<!-- %s begin -->" % tag + chr(10), "<!-- %s end -->" % tag
    if b not in text:
        return text
    i, j = text.index(b) + len(b), text.index(e)
    return text[:i] + body + text[j:]


def main():
    with open(MPC_JSON, encoding="utf-8") as fh:
        d = json.load(fh)
    with open(VALUES, encoding="utf-8", newline="") as fh:
        s = fh.read()
    blk = values_block(d)
    if BEGIN not in s:
        s = s.rstrip("\n") + "\n" + blk
    else:
        i, j = s.index(BEGIN), s.index(END) + len(END)
        s = s[:i] + blk + s[j:]
    with open(VALUES, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(s)
    with open(DOC, encoding="utf-8", newline="") as fh:
        t = fh.read()
    if "wave_pilot_exp" in d:
        t = _replace(t, "pilot_loop_keys", pilot_table(d["wave_pilot_exp"]["results"],
                                                       d.get("wave_pilot_trials", {}).get("results", [])))
