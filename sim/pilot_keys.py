"""Record keys and key tables of the pilot's choice, the powered leg over swell and the reflex redesign.

python -m sim.pilot_keys   rewrites the block of record/values.yaml between its two marker comments with one key per
result of the pilot experiment over swell (sim/out/mpc.json keys wave_pilot_exp and wave_pilot_trials, against the
earlier wave_loop_exp), of the powered-leg navigation runs (wave_leg_exp) and of the reflex (reflex_exp,
nav_exp_reflex2, wave_pilot_reflex_exp), and the key tables of docs/02-form.md between the pilot_keys markers (the
prose cites the keys, never the numbers).

Key names:
- wave.pilot_<aircraft>_hs<H>_<along|against|calm>_u<U>_<p63|p64>_<field>: the runs with the pilot's choice by trial;
  fields as the loop's (sim.wave_keys) plus forward_face_share (after the entry), trial_cost_w (the chosen trial's
  cost) and choice_course_deg (the chosen entry's course relative to the swell; absent for the flat leg).
- wave.pilot_<field>: the summary of those runs and their comparison with the earlier runs (pilot_summary).
- wave.leg_<target>_<leg>_<field>: the navigation runs over swell with the powered legs (sim.wavelib.WAVE_LEGS); the
  fields are those of sim.wave_keys.nav_values.
- reflex.<dive|contact>_<truth|flat>_<none|v1|v2>_<field>: the constructed cases (sim.reflex.reflex_summary).
- reflex.nav_<field> and reflex.nav<5|10>_<aircraft>_u<U>_<target>_<field>: the flat-sea navigation runs with the
  redesigned reflex, against nav_exp and nav_exp_10km.
- reflex.loop_<field> and reflex.loop_<case>_<field>: the runs over swell with the redesigned reflex, against the
  pilot runs without it.
"""
import json
import os

from sim.wave_keys import PSHORT, SHORT, _num, nav_values

HERE = os.path.dirname(__file__)
ROOT = os.path.dirname(HERE)
MPC_JSON = os.path.join(HERE, "out", "mpc.json")
VALUES = os.path.join(ROOT, "record", "values.yaml")
DOC = os.path.join(ROOT, "docs", "02-form.md")
BEGIN = "  # generated by python -m sim.pilot_keys: begin\n"
END = "  # generated by python -m sim.pilot_keys: end\n"
SEC_WAVE = "docs/02-form.md#wave-loop"
SEC_REFLEX = "docs/02-form.md#receding-horizon"
PILOT_FIELDS = (("aloft_s", "s"), ("counted", "1"), ("power_w", "W"), ("power_after_w", "W"), ("motor_share", "1"),
                ("height_median_m", "m"), ("forward_face_share", "1"), ("trial_cost_w", "W"))
KIND_LABEL = {"soaring|crest": "crest ride", "motor|crest": "motor crest ride", "soaring|cycle": "soaring cycle",
              "motor|cycle": "motor cycle"}


def _key(k, v, unit, sec):
    return ("  - key: %s\n    v: %s\n    unit: %s\n    status: calculated\n    basis:\n      - %s\n" % (k, v, unit, sec))


def case_of(r):
    return (r["aircraft"], r["hs"], r["direction"], r["u10"], r["preset"])


def case_id(r):
    d = "calm" if r["u10"] == 0.0 else r["direction"]
    return "%s_hs%s_%s_u%g_%s" % (SHORT[r["aircraft"]], _num(r["hs"]), d, r["u10"], PSHORT[r["preset"]])


def _median(xs):
    xs = sorted(xs)
    if not xs:
        return None
    n = len(xs)
    return xs[n // 2] if n % 2 else 0.5 * (xs[n // 2 - 1] + xs[n // 2])


def trial_of(trials, r):
    for t in trials:
        if case_of(t) == case_of(r) and t["key"] == r.get("choice"):
            return t
    return None


def pilot_values(rows, trials, prefix="pilot"):
    out = {}
    for r in rows:
        a = r.get("after_entry") or {}
        t = trial_of(trials, r)
        v = {"aloft_s": round(r["survival_s"], 0), "counted": int(r["margins"]["counts"]),
             "power_w": round(r["motor"]["avg_power_w"], 1),
             "power_after_w": round(a["avg_power_w"], 1) if a else None,
             "motor_share": round(r["motor"]["thrust_on_share"], 2),
             "height_median_m": round(r["margins"]["height_median_m"], 1),
             "forward_face_share": round(a["forward_face_share"], 2) if a else None,
             "trial_cost_w": round(t["cost_w"], 1) if (t and t["cost_w"] < 1000.0) else None}
        for f, u in PILOT_FIELDS:
            if v[f] is not None:
                out["%s_%s_%s" % (prefix, case_id(r), f)] = (v[f], u)
        if r.get("choice"):
            out["%s_%s_choice_course_deg" % (prefix, case_id(r))] = (round(float(r["choice"].split("|")[2]), 1), "deg")
    return out


def _power(r):
    """The run's power after the entry, or over the run where there was no entry."""
    a = r.get("after_entry")
    return a["avg_power_w"] if a else r["motor"]["avg_power_w"]


def pilot_summary(rows, earlier, trials, prefix="pilot"):
    """Summary keys of the pilot runs, and their comparison case by case with the earlier runs (wave_loop_exp)."""
    by = {case_of(r): r for r in earlier}
    full = [r for r in rows if r["ended"] == "complete"]
    cnt = [r for r in rows if r["margins"]["counts"]]
    flat = [r for r in rows if not r.get("choice")]
    rat = sorted(_power(r) / r["flat"]["power_avg_w"] for r in cnt if r.get("flat") and r["flat"]["power_avg_w"] > 0)
    pw = [_power(r) for r in cnt]
    share = [r["motor"]["thrust_on_share"] for r in cnt]
    u3 = [r for r in rows if r["u10"] == 3.0]
    u3e = [by[case_of(r)] for r in u3 if case_of(r) in by]
    tip_e = [e for e in earlier if e["ended"] == "tip contact"]
    tip_now = [r for r in rows if case_of(r) in {case_of(e) for e in tip_e}]
    pairs = [(by[case_of(r)], r) for r in rows if case_of(r) in by]
    out = {"runs": (len(rows), "1"), "full": (len(full), "1"), "counted": (len(cnt), "1"),
           "counted_p63": (sum(r["preset"] == "p63" for r in cnt), "1"),
           "counted_p64": (sum(r["preset"] == "p64_low" for r in cnt), "1"),
           "ended_early": (len(rows) - len(full), "1"),
           "flat_choice": (len(flat), "1"), "flat_choice_ended": (sum(r["ended"] != "complete" for r in flat), "1"),
           "gained": (sum(bool(r["margins"]["counts"]) and not bool(e["margins"]["counts"]) for e, r in pairs), "1"),
           "lost": (sum(bool(e["margins"]["counts"]) and not bool(r["margins"]["counts"]) for e, r in pairs), "1"),
           "ended_now_not_before": (sum(e["ended"] == "complete" and r["ended"] != "complete" for e, r in pairs), "1"),
           "complete_now_not_before": (sum(e["ended"] != "complete" and r["ended"] == "complete" for e, r in pairs), "1"),
           "power_lower_runs": (sum(r["motor"]["avg_power_w"] < 0.9 * e["motor"]["avg_power_w"] for e, r in pairs), "1"),
           "power_higher_runs": (sum(r["motor"]["avg_power_w"] > 1.1 * e["motor"]["avg_power_w"] for e, r in pairs),
                                 "1"),
           "u3_power_max_w": (round(max(r["motor"]["avg_power_w"] for r in u3), 1), "W") if u3 else None,
           "u3_power_median_w": (round(_median([r["motor"]["avg_power_w"] for r in u3]), 1), "W") if u3 else None,
           "u3_earlier_power_median_w": (round(_median([e["motor"]["avg_power_w"] for e in u3e]), 1), "W") if u3e else None,
           "u3_dearer_runs": (sum(bool(r.get("flat")) and _power(r) > r["flat"]["power_avg_w"] for r in u3), "1"),
           "u3_counted": (sum(bool(r["margins"]["counts"]) for r in u3), "1"),
           "u3_earlier_counted": (sum(bool(e["margins"]["counts"]) for e in u3e), "1"),
           "tip_cases": (len(tip_e), "1"),
           "tip_cases_complete": (sum(r["ended"] == "complete" for r in tip_now), "1"),
           "tip_cases_counted": (sum(bool(r["margins"]["counts"]) for r in tip_now), "1"),
           "power_median_all_w": (round(_median([r["motor"]["avg_power_w"] for r in rows]), 1), "W"),
           "earlier_power_median_all_w": (round(_median([e["motor"]["avg_power_w"] for e, _ in pairs]), 1), "W")}
    if rat:
        out.update({"ratio_min": (round(rat[0], 3), "1"), "ratio_median": (round(_median(rat), 2), "1"),
                    "ratio_max": (round(rat[-1], 2), "1")})
    if pw:
        out.update({"power_min_w": (round(min(pw), 1), "W"), "power_median_w": (round(_median(pw), 1), "W"),
                    "motor_share_min": (round(min(share), 3), "1"), "motor_share_median": (round(_median(share), 2), "1"),
                    "low_motor_runs": (sum(s <= 0.1 for s in share), "1")})
    ff = [r["after_entry"]["forward_face_share"] for r in rows if r.get("after_entry") and r.get("choice")
          and "|crest|" in r["choice"]]
    if ff:
        out["crest_forward_face_median"] = (round(_median(ff), 2), "1")
        out["crest_forward_face_min"] = (round(min(ff), 2), "1")
    if trials:
        ch = [trial_of(trials, r) for r in rows]
        dif = [abs(t["cost_w"] - _power(r)) for t, r in zip(ch, rows) if t and t["cost_w"] < 1000.0]
        out["trials"] = (len(trials), "1")
        if dif:
            out["trial_error_median_w"] = (round(_median(dif), 1), "W")
            out["trial_error_max_w"] = (round(max(dif), 1), "W")
        out["choice_crest"] = (sum(bool(r.get("choice")) and "|crest|" in r["choice"] for r in rows), "1")
        out["choice_cycle"] = (sum(bool(r.get("choice")) and "|cycle|" in r["choice"] for r in rows), "1")
        same = 0
        for e, r in pairs:
            ee = e.get("entry") or {}
            if not r.get("choice"):
                same += int(not ee.get("kind"))
                continue
            k = r["choice"].split("|")
            same += int(bool(ee.get("kind")) and ee["kind"] == k[0] and bool(ee.get("crest")) == (k[1] == "crest")
                        and abs(abs(float(ee["course_rel_deg"])) - abs(float(k[2]))) < 1e-3)
        out["choice_same_as_earlier"] = (same, "1")
    return {"%s_%s" % (prefix, k): v for k, v in out.items() if v is not None}


def pilot_table(rows, trials, prefix="pilot"):
    have = pilot_values(rows, trials, prefix)
    fields = list(PILOT_FIELDS) + [("choice_course_deg", "deg")]
    lines = ["| aircraft | Hs | swell | u10 | wave wind | choice | " + " | ".join(f.replace("_", " ") for f, _ in fields)
             + " |", "|" + "---|" * (6 + len(fields))]
    for r in rows:
        cid = "%s_%s" % (prefix, case_id(r))
        ch = r.get("choice")
        lab = "flat leg" if not ch else KIND_LABEL["|".join(ch.split("|")[:2])]
        cells = [("wave.%s_%s" % (cid, f)) if ("%s_%s" % (cid, f)) in have else "n/a" for f, _ in fields]
        lines.append("| %s | %g | %s | %g | %s | %s | " % (SHORT[r["aircraft"]], r["hs"],
                                                            "calm" if r["u10"] == 0.0 else r["direction"], r["u10"],
                                                            PSHORT[r["preset"]], lab) + " | ".join(cells) + " |")
    return chr(10).join(lines) + chr(10)


def track_off(r, window_s=240.0):
    """(min, max) over windows of window_s of the median angle (deg) between the ground track (the logged track
    points, every 5 s) and the commanded bearing; the heading fields of nav_values compare the heading through the
    air and so carry the crab angle of the wind triangle."""
    import numpy as np
    nv = r.get("nav") or {}
    tr, cm = np.asarray(nv.get("track") or [], float), nv.get("commands") or []
    if len(tr) < 3 or not cm:
        return None
    ct = np.array([c[0] for c in cm])
    brg = np.array([c[1] for c in cm])
    v = np.diff(tr[:, 1:], axis=0)
    t = tr[1:, 0]
    course = np.degrees(np.arctan2(v[:, 0], v[:, 1])) % 360.0
    j = np.clip(np.searchsorted(ct, tr[:-1, 0], side="right") - 1, 0, len(cm) - 1)
    off = np.abs((course - brg[j] + 180.0) % 360.0 - 180.0)
    win = [float(np.median(off[(t >= a) & (t < a + window_s)])) for a in np.arange(0.0, t[-1], window_s)
           if np.sum((t >= a) & (t < a + window_s)) > 3]
    return (min(win), max(win)) if win else None


def leg_rows(d):
    """The powered-leg runs (wave_leg_exp) and the recorded runs of wave_nav_exp as leg "surface"."""
    rows = [dict(r, leg="surface") for r in d.get("wave_nav_exp", {}).get("results", []) if "leg" not in r]
    have = {(r["target_rel_swell"], r["leg"]) for r in d.get("wave_leg_exp", {}).get("results", [])}
    rows = [r for r in rows if (r["target_rel_swell"], r["leg"]) not in have]
    order = {"across": 0, "against": 1, "with": 2}
    lorder = {"surface": 0, "surface_hold": 1, "msl_hold": 2}
    rows += d.get("wave_leg_exp", {}).get("results", [])
    return sorted(rows, key=lambda r: (order[r["target_rel_swell"]], lorder[r["leg"]]))


def leg_values(rows):
    out = {}
    for r in rows:
        base = "leg_%s_%s_" % (r["target_rel_swell"], r["leg"])
        for k, v in nav_values(r).items():
            out[base + k[4:]] = v
        to = track_off(r)
        if to is not None:
            out[base + "track_off_min_deg"] = (round(to[0], 0), "deg")
            out[base + "track_off_max_deg"] = (round(to[1], 0), "deg")
    return out


def leg_table(rows):
    fields = ("arrival_s", "reached", "counted", "vmg_ms", "energy_wh", "motor_share", "height_median_m",
              "height_min_m", "wingtip_min_m", "below_stall_s", "track_off_max_deg", "heading_off_max_deg")
    have = leg_values(rows)
    lines = ["| target | leg | " + " | ".join(f.replace("_", " ") for f in fields) + " |",
             "|" + "---|" * (2 + len(fields))]
    for r in rows:
        base = "leg_%s_%s_" % (r["target_rel_swell"], r["leg"])
        lines.append("| %s the swell | %s | " % (r["target_rel_swell"], r["leg"].replace("_", " "))
                     + " | ".join(("wave." + base + f) if (base + f) in have else "n/a" for f in fields) + " |")
    return chr(10).join(lines) + chr(10)


REFLEX_FIELDS = (("cases", "1"), ("base_contacts", "1"), ("contacts", "1"), ("fired", "1"), ("rescues", "1"),
                 ("false_firings", "1"), ("loops", "1"), ("gamma_max_deg", "deg"), ("v_min_over_stall", "1"),
                 ("touched", "1"), ("tip_depth_max_m", "m"))


def reflex_values(summary):
    out = {}
    for k, v in summary.items():
        for f, u in REFLEX_FIELDS:
            x = v[f]
            out["%s_%s" % (k, f)] = (round(x, 3) if isinstance(x, float) else x, u)
    return out


def reflex_table(summary):
    lines = ["| case | prediction world | reflex | " + " | ".join(f.replace("_", " ") for f, _ in REFLEX_FIELDS) + " |",
             "|" + "---|" * (3 + len(REFLEX_FIELDS))]
    for k in summary:
        fam, w, v = k.split("_")
        lines.append("| %s | %s | %s | " % (fam, w, {"none": "none", "v1": "first", "v2": "redesigned"}[v])
                     + " | ".join("reflex.%s_%s" % (k, f) for f, _ in REFLEX_FIELDS) + " |")
    return chr(10).join(lines) + chr(10)


def nav_case_id(r, dist):
    return "nav%d_%s_u%g_%s" % (round(dist / 1000.0), SHORT[r["aircraft"]], r["u10"], r["direction"])


def reflex_nav_values(rows_r, rows_0, dist):
    """Per run: the firings, the time in the reflex, whether it counted and its energy, with the run without the
    reflex beside it; and the totals."""
    by = {(r["aircraft"], r["u10"], r["direction"]): r for r in rows_0}
    out = {}
    tot = {"runs": 0, "fired_runs": 0, "firings": 0, "counted": 0, "counted_without": 0}
    for r in rows_r:
        b = by.get((r["aircraft"], r["u10"], r["direction"]))
        rf = r.get("reflex") or {}
        nv = r.get("nav") or {}
        cid = nav_case_id(r, dist)
        out["%s_firings" % cid] = (int(rf.get("n", 0)), "1")
        out["%s_reflex_s" % cid] = (round(float(rf.get("total_s", 0.0)), 2), "s")
        out["%s_counted" % cid] = (int(bool(nv.get("counts_as_arrived"))), "1")
        out["%s_energy_wh" % cid] = (round(r["motor"]["energy_wh"], 2), "Wh")
        tot["runs"] += 1
        tot["fired_runs"] += int(rf.get("n", 0) > 0)
        tot["firings"] += int(rf.get("n", 0))
        tot["counted"] += int(bool(nv.get("counts_as_arrived")))
        if b is not None:
            tot["counted_without"] += int(bool((b.get("nav") or {}).get("counts_as_arrived")))
    pre = "nav%d" % round(dist / 1000.0)
    out.update({"%s_%s" % (pre, k): (v, "1") for k, v in tot.items()})
    return out


def reflex_loop_values(rows_r, rows_0):
    """The runs over swell with the redesigned reflex against the same pilot runs without it."""
    by = {case_of(r): r for r in rows_0}
    pairs = [(by[case_of(r)], r) for r in rows_r if case_of(r) in by]
    out = {}
    fired = [r for _, r in pairs if (r.get("reflex") or {}).get("n", 0) > 0]
    causes = {}
    for _, r in pairs:
        for c, n in ((r.get("reflex") or {}).get("causes") or {}).items():
            causes[c] = causes.get(c, 0) + n
    tot = {"runs": len(pairs), "fired_runs": len(fired),
           "firings": sum((r.get("reflex") or {}).get("n", 0) for _, r in pairs),
           "rescues": sum(b["ended"] != "complete" and r["ended"] == "complete" for b, r in pairs),
           "worse": sum(b["ended"] == "complete" and r["ended"] != "complete" for b, r in pairs),
           "counted": sum(bool(r["margins"]["counts"]) for _, r in pairs),
           "counted_without": sum(bool(b["margins"]["counts"]) for b, _ in pairs),
           "gained": sum(bool(r["margins"]["counts"]) and not bool(b["margins"]["counts"]) for b, r in pairs),
           "lost": sum(bool(b["margins"]["counts"]) and not bool(r["margins"]["counts"]) for b, r in pairs)}
    out.update({"loop_%s" % k: (v, "1") for k, v in tot.items()})
    for c, n in causes.items():
        out["loop_cause_%s" % c] = (n, "1")
    rs = [float((r.get("reflex") or {}).get("total_s", 0.0)) for _, r in pairs]
    if rs:
        out["loop_reflex_s_max"] = (round(max(rs), 2), "s")
    for b, r in pairs:
        rf = r.get("reflex") or {}
        cid = "loop_%s" % case_id(r)
        out["%s_firings" % cid] = (int(rf.get("n", 0)), "1")
        out["%s_counted" % cid] = (int(bool(r["margins"]["counts"])), "1")
        out["%s_aloft_s" % cid] = (round(r["survival_s"], 0), "s")
        out["%s_power_w" % cid] = (round(r["motor"]["avg_power_w"], 1), "W")
    return out


