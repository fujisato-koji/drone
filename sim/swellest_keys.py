"""Record keys and the key tables of the sea estimation (Q-064, stage 2 of the flight over swell).

python -m sim.swellest_keys   rewrites the block of record/values.yaml between its two marker comments with one key
per result of sim/out/swellest.json (keys "errors" and "loop" of python -m sim.swellest), and the key tables of
docs/02-form.md#sea-estimation between their swellest_* markers (the values show in the generated value table of
docs/01-requirements.md; the prose cites the keys, never the numbers).

Key names (set: a sensor set of sim.swellest.SENSOR_SETS; T: the check time in s since the start):
- est.set_<set>_mass_g, est.set_<set>_power_w: the sensors of a set (range sensors and navigation sensors).
- est.reg_<set>_t<T>_<phase|height>_p90_<mid|worst>: the regular seas of the error grid (heights, periods and
  directions); for each sea the 90th percentile over its seeds and the 10 s before T of the absolute phase error
  (rad) or of the absolute height error (a fraction of the swell's amplitude, Hs / 2 of the oracle swell), then the
  median (mid) and the largest (worst) over the seas; est.reg_<set>_ready_share: the share of the runs with a ready
  estimate at the last check.
- est.regsea_<set>_hs<H>_tp<P>_<dir>_t<T>_<phase_p90|height_p90>: one regular sea.
- est.irr_<sea>_<set>_t<T>_<phase_p90|height_p90|ahead_m>: the irregular and mixed seas, sea irregular_hs<H>_<dir>,
  swellws_hs<H>_<dir> or mixed_<dir> (ahead_m: the median rms error of the surface over the next 3 s of the path, m).
  Heights are fractions of the swell's amplitude (the amplitude of the regular wave with its energy).
- est.orc_hs<H>_<set>_t<T>_<phase_p90|height_p90>: the oracle loop's own path (no survey).
- est.loop_<set>_hs<H>_<field>: the closed loop with the estimated sea; fields counted, aloft_s, power_w,
  power_after_w, motor_share, height_median_m, t_ready_s, t_entry_s, phase_p90 and height_p90 (from the entry on),
  pred_rms_m (fly_mpc's rms error of the planner's surface along its plans).
"""
import json
import os

import numpy as np

HERE = os.path.dirname(__file__)
ROOT = os.path.dirname(HERE)
OUT_JSON = os.path.join(HERE, "out", "swellest.json")
VALUES = os.path.join(ROOT, "record", "values.yaml")
DOC = os.path.join(ROOT, "docs", "02-form.md")
BEGIN = "  # generated by python -m sim.swellest_keys: begin\n"
END = "  # generated by python -m sim.swellest_keys: end\n"
SECTION = "docs/02-form.md#sea-estimation"
CHECKS = (60.0, 120.0, 300.0)       # the first estimate comes after the survey (46 s), so none at 30 s
IRR_CHECKS = (60.0, 300.0)
IRR_SETS = ("radar_tips_rtk", "tips_rtk", "radar_tips_fwd_rtk", "radar_tips_fwd_baro", "radar_tips_baro", "lidar_rtk")
REGSEA_SETS = ("radar_tips_rtk", "radar_tips_fwd_baro")
SEA_NAME = {"irregular": "irregular", "swell_windsea": "swellws", "mixed": "mixed"}
LOOP_FIELDS = (("counted", "1"), ("aloft_s", "s"), ("power_w", "W"), ("power_after_w", "W"), ("motor_share", "1"),
               ("height_median_m", "m"), ("t_ready_s", "s"), ("t_entry_s", "s"), ("phase_p90", "rad"),
               ("height_p90", "1"), ("pred_rms_m", "m"))


def _irr_name(sea, hs, direction):
    """The sea part of an irregular key: the sea history's sea has its own height, so no Hs in its name."""
    if sea == "mixed":
        return "mixed_%s" % direction
    return "%s_hs%s_%s" % (SEA_NAME[sea], _num(hs), direction)


def _num(v):
    return ("%g" % v).replace(".", "p").replace("-", "m")


def _key(k, v, unit):
    return ("  - key: %s\n    v: %s\n    unit: %s\n    status: calculated\n    basis:\n      - %s\n"
            % (k, v, unit, SECTION))


def _r(v, nd=3):
    return None if v is None else round(float(v), nd)


def _load():
    with open(OUT_JSON, encoding="utf-8") as fh:
        return json.load(fh)


def _summ(d, sea, path, set_name, hs=None, tp=None, direction=None):
    return [s for s in d["errors"]["summary"] if s["sea"] == sea and s["path"] == path and s["set"] == set_name
            and (hs is None or s["hs"] == hs) and (tp is None or s["tp"] == tp)
            and (direction is None or s["direction"] == direction)]


def pooled(d, set_name):
    """The regular seas of one set: {check: (median and largest over the seas of their phase p90, the same of their
    height p90, n seas with an estimate, n seas)} and the ready share at the last check."""
    ss = _summ(d, "regular", "survey_ride", set_name)
    out = {}
    for tc in CHECKS:
        c = [s["checks"]["%g" % tc] for s in ss]
        ph = [x["phase_p90"] for x in c if x["phase_p90"] is not None]
        hh = [x["height_p90"] for x in c if x["height_p90"] is not None]
        out[tc] = (float(np.median(ph)) if ph else None, float(np.max(ph)) if ph else None,
                   float(np.median(hh)) if hh else None, float(np.max(hh)) if hh else None, len(ph), len(c))
    rdy = [s["checks"]["%g" % CHECKS[-1]]["ready_share"] for s in ss]
    return out, (float(np.mean(rdy)) if rdy else 0.0)


def loop_row(r):
    """The closed-loop fields of one run."""
    a = r.get("after_entry") or {}
    rows = np.asarray(r.get("rows") or [], float)
    t_in = a.get("t_entry_s")
    ph = hh = None
    if len(rows) and t_in is not None:
        m = rows[:, 0] >= t_in
        if m.any():
            ph = float(np.percentile(np.abs(rows[m, 1]), 90))
            a_est = (rows[m, 2] + 1.0) * rows[m, 8]
            hh = float(np.percentile(np.abs(a_est - rows[m, 8]) / r["a_ref"], 90))
    return {"counted": int(bool(r["margins"]["counts"])), "aloft_s": _r(r["survival_s"], 1),
            "power_w": _r(r["motor"]["avg_power_w"], 1), "power_after_w": _r(a.get("avg_power_w"), 1),
            "motor_share": _r(r["motor"]["thrust_on_share"], 2),
            "height_median_m": _r(r["margins"]["height_median_m"], 1), "t_ready_s": _r(r.get("t_ready"), 1),
            "t_entry_s": _r(t_in, 1), "phase_p90": _r(ph), "height_p90": _r(hh),
            "pred_rms_m": _r(r.get("eta_pred_rms"))}


def values_block():
    from sim.swellest import SENSOR_SETS, set_mass_power
    d = _load()
    lines = []
    for s_ in SENSOR_SETS:
        m, p = set_mass_power(s_)
        lines.append(_key("est.set_%s_mass_g" % s_, _r(m, 1), "g"))
        lines.append(_key("est.set_%s_power_w" % s_, _r(p, 2), "W"))
    if "errors" in d:
        for s_ in SENSOR_SETS:
            pl, rdy = pooled(d, s_)
            for tc in CHECKS:
                ph, phw, hh, hhw, _, _ = pl[tc]
                if ph is not None:
                    b = "est.reg_%s_t%s_" % (s_, _num(tc))
                    lines.append(_key(b + "phase_p90_mid", _r(ph), "rad"))
                    lines.append(_key(b + "phase_p90_worst", _r(phw), "rad"))
                    lines.append(_key(b + "height_p90_mid", _r(hh), "1"))
                    lines.append(_key(b + "height_p90_worst", _r(hhw), "1"))
            lines.append(_key("est.reg_%s_ready_share" % s_, _r(rdy, 2), "1"))
        for s_ in REGSEA_SETS:
            for x in _summ(d, "regular", "survey_ride", s_):
                for tc in (120.0, 300.0):
                    c = x["checks"]["%g" % tc]
                    base = "est.regsea_%s_hs%s_tp%s_%s_t%s" % (s_, _num(x["hs"]), _num(x["tp"]), x["direction"], _num(tc))
                    if c["phase_p90"] is not None:
                        lines.append(_key(base + "_phase_p90", _r(c["phase_p90"]), "rad"))
                        lines.append(_key(base + "_height_p90", _r(c["height_p90"]), "1"))
        for x in d["errors"]["summary"]:
            if x["sea"] in SEA_NAME and x["set"] in IRR_SETS:
                for tc in IRR_CHECKS:
                    c = x["checks"]["%g" % tc]
                    base = "est.irr_%s_%s_t%s" % (_irr_name(x["sea"], x["hs"], x["direction"]), x["set"], _num(tc))
                    if c["phase_p90"] is not None:
                        lines.append(_key(base + "_phase_p90", _r(c["phase_p90"]), "rad"))
                        lines.append(_key(base + "_height_p90", _r(c["height_p90"]), "1"))
                        lines.append(_key(base + "_ahead_m", _r(c["ahead_median_m"]), "m"))
            if x["path"] == "oracle":
                for tc in IRR_CHECKS:
                    c = x["checks"]["%g" % tc]
                    base = "est.orc_hs%s_%s_t%s" % (_num(x["hs"]), x["set"], _num(tc))
                    if c["phase_p90"] is not None:
                        lines.append(_key(base + "_phase_p90", _r(c["phase_p90"]), "rad"))
                        lines.append(_key(base + "_height_p90", _r(c["height_p90"]), "1"))
    if "loop" in d:
        for r in d["loop"]["results"]:
            if r.get("seed", 0) != 0:
                continue
            f = loop_row(r)
            for name, unit in LOOP_FIELDS:
                if f[name] is not None:
                    lines.append(_key("est.loop_%s_hs%s_%s" % (r["set"], _num(r["hs"]), name), f[name], unit))
    return "".join(lines)


def sets_table():
    from sim.swellest import SENSOR_SETS
    nav = {"standalone": "GNSS without corrections, IMU", "standalone_vw": "the same, white GNSS velocity error",
           "baro": "GNSS without corrections, IMU, barometer", "rtk": "RTK GNSS, IMU, barometer"}
    rng = {"lidar": "laser altimeter", "radar": "radar altimeter", "tip_r": "tip radar", "tip_l": "tip radar",
           "forward": "forward radar"}
    lines = ["| set | range sensors | navigation | mass g | power W |", "|---|---|---|---|---|"]
    for s_, (rs, nk) in SENSOR_SETS.items():
        names = []
        for r in rs:
            if rng[r] not in names:
                names.append(rng[r])
        lines.append("| %s | %s | %s | est.set_%s_mass_g | est.set_%s_power_w |" % (
            s_, ", ".join(("two " + n + "s") if n == "tip radar" else n for n in names), nav[nk], s_, s_))
    return "\n".join(lines)


def reg_table():
    from sim.swellest import SENSOR_SETS
    head = ["set", "at", "phase p90, median sea", "phase p90, worst sea", "height p90, median sea",
            "height p90, worst sea", "ready at the end"]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for s_ in SENSOR_SETS:
        for t in CHECKS:
            b = "est.reg_%s_t%s_" % (s_, _num(t))
            lines.append("| %s | %g s | %sphase_p90_mid | %sphase_p90_worst | %sheight_p90_mid | %sheight_p90_worst | %s |"
                         % (s_, t, b, b, b, b, ("est.reg_%s_ready_share" % s_) if t == CHECKS[-1] else ""))
    return "\n".join(lines)


def regsea_table():
    from sim.swellest import ERR_DIRS, ERR_HS, ERR_TP
    lines = ["| set | Hs | Tp | swell | phase p90 at 120 s | height p90 at 120 s | phase p90 at 300 s | "
             "height p90 at 300 s |", "|---|---|---|---|---|---|---|---|"]
    for s_ in REGSEA_SETS:
        for hs in ERR_HS:
            for tp in ERR_TP:
                for dr in ERR_DIRS:
                    b = "est.regsea_%s_hs%s_tp%s_%s_t" % (s_, _num(hs), _num(tp), dr)
                    lines.append("| %s | %g | %g | %s | %s120_phase_p90 | %s120_height_p90 | %s300_phase_p90 | "
                                 "%s300_height_p90 |" % (s_, hs, tp, dr, b, b, b, b))
    return "\n".join(lines)


def irr_table():
    from sim.swellest import ERR_IRREGULAR
    label = {"irregular": "irregular long-crested swell", "swell_windsea": "irregular swell and wind sea",
             "mixed": "sea history (short-crested swell and wind sea)"}
    lines = ["| sea | Hs | swell | set | phase p90 at 60 s | height p90 at 60 s | phase p90 at 300 s | "
             "height p90 at 300 s | surface ahead at 300 s m |", "|---|---|---|---|---|---|---|---|---|"]
    for kind, hs, tp, dr in ERR_IRREGULAR:
        for s_ in IRR_SETS:
            b = "est.irr_%s_%s_t" % (_irr_name(kind, hs, dr), s_)
            lines.append("| %s | %s | %s | %s | %s60_phase_p90 | %s60_height_p90 | %s300_phase_p90 | %s300_height_p90 | "
                         "%s300_ahead_m |" % (label[kind], "its own" if kind == "mixed" else "%g" % hs, dr, s_, b, b, b,
                                             b, b))
    return "\n".join(lines)


def orc_table():
    from sim.swellest import SENSOR_SETS
    lines = ["| Hs | set | phase p90 at 60 s | height p90 at 60 s | phase p90 at 300 s | height p90 at 300 s |",
             "|---|---|---|---|---|---|"]
    for hs in (3.0, 2.0):
        for s_ in SENSOR_SETS:
            b = "est.orc_hs%s_%s_t" % (_num(hs), s_)
            lines.append("| %g | %s | %s60_phase_p90 | %s60_height_p90 | %s300_phase_p90 | %s300_height_p90 |"
                         % (hs, s_, b, b, b, b))
    return "\n".join(lines)


def loop_table():
    d = _load()
    head = ["planner's sea", "Hs", "ready s", "entry s", "counted", "aloft s", "power after w", "motor share",
            "height median m", "phase p90", "height p90", "surface rms m"]
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for hs in (3.0, 2.0):
        o = "wave.loop_albatross_hs%s_along_u6_p63_" % _num(hs)
        lines.append("| oracle | %g | n/a | n/a | %scounted | %saloft_s | %spower_after_w | %smotor_share | "
                     "%sheight_median_m | n/a | n/a | n/a |" % (hs, o, o, o, o, o))
        for r in d.get("loop", {}).get("results", []):
            if r["hs"] != hs or r.get("seed", 0) != 0:
                continue
            f = loop_row(r)
            b = "est.loop_%s_hs%s_" % (r["set"], _num(hs))
            cells = ["estimated, " + r["set"], "%g" % hs] + [
                (b + n) if f[n] is not None else "n/a" for n in ("t_ready_s", "t_entry_s", "counted", "aloft_s",
                                                                  "power_after_w", "motor_share", "height_median_m",
                                                                  "phase_p90", "height_p90", "pred_rms_m")]
            lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _replace(text, tag, body):
    b, e = "<!-- %s begin -->" % tag + chr(10), "<!-- %s end -->" % tag
    i, j = text.find(b), text.find(e)
    if i < 0 or j < 0:
        return text
    return text[:i + len(b)] + body + chr(10) + text[j:]


def main():
    with open(VALUES, encoding="utf-8", newline="") as fh:
        text = fh.read().replace("\r\n", "\n")
    if BEGIN not in text or END not in text:
        raise SystemExit("add the two marker comment lines to record/values.yaml first")
    i, j = text.index(BEGIN) + len(BEGIN), text.index(END)
    text = text[:i] + values_block() + text[j:]
    with open(VALUES, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    with open(DOC, encoding="utf-8", newline="") as fh:
        doc = fh.read().replace("\r\n", "\n")
    d = _load()
    doc = _replace(doc, "swellest_sets", sets_table())
    if "errors" in d:
        doc = _replace(doc, "swellest_reg", reg_table())
        doc = _replace(doc, "swellest_regsea", regsea_table())
        doc = _replace(doc, "swellest_irr", irr_table())
        doc = _replace(doc, "swellest_orc", orc_table())
    if "loop" in d:
        doc = _replace(doc, "swellest_loop", loop_table())
    with open(DOC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(doc)
    print("values and tables written")


if __name__ == "__main__":
    main()
