def table_navcmp(ks):
    _, rows = nav_cmp_keys()
    L = [_row(["closed-loop run", "plan's mode", "plan's speed", "closed-loop VMG", "counted", "VMG over the plan's speed"]),
         "|---|---|---|---|---|---|"]
    for cid, r, mode, counted in rows:
        L.append(_row([cid, mode, f"route.cmp_{cid}_plan_ms", f"nav.{cid}_vmg_ms", f"nav.{cid}_counted", f"route.cmp_{cid}_ratio"]))
    return L


TABLES = {"settings": table_settings, "night": table_night, "exp": table_exp, "navcmp": table_navcmp}


def main():
    ks = keys()
    with open(VALUES, encoding="utf-8", newline="") as fh:
        s = fh.read()
    if BEGIN in s:
        i, j = s.index(BEGIN), s.index(END) + len(END)
        s = s[:i] + values_block(ks) + s[j:]
    else:
        s = s.rstrip("\n") + "\n" + values_block(ks)
    with open(VALUES, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(s)
    with open(DOC, encoding="utf-8", newline="") as fh:
        t = fh.read()
    for name, fn in TABLES.items():
        b, e = f"<!-- route_keys {name} begin -->\n", f"<!-- route_keys {name} end -->"
        if b not in t:
            raise SystemExit(f"add the markers of the {name} table to docs/02-form.md first")
        i, j = t.index(b) + len(b), t.index(e)
        t = t[:i] + "\n".join(fn(ks)) + "\n" + t[j:]
    with open(DOC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(t)
    print(f"wrote {len(ks)} keys")


if __name__ == "__main__":
    main()
