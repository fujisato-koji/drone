          ("route.usable_depth", RT.USABLE_DEPTH, "1", a, q), ("route.reserve_fraction", RT.RESERVE_FRACTION, "1", a, q),
          ("route.night_draw_w", RT.NIGHT_DRAW_W, "W", a, q23), ("route.takeoff_run_s", RT.TAKEOFF_RUN_S, "s", a, q),
          ("route.refine", RT.REFINE, "1", a, q), ("route.rings", RT.RINGS, "1", a, q), ("route.sub_km", RT.SUB_KM, "km", a, q),
