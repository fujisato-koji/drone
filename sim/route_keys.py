def values_block(ks):
    lines = [BEGIN]
    for k, v, u, st, basis in ks:
        bl = "".join(f"      - {b}\n" for b in basis)
        lines.append(f"  - key: {k}\n    v: {v}\n    unit: {u}\n    status: {st}\n    basis:\n{bl}")
    lines.append(END)
    return "".join(lines)


def _row(cells):
    return "| " + " | ".join(str(x) for x in cells) + " |"


def table_night(ks):
    head = ["case", "night", "night at the night draw", "the rule's night", "carried", "capacity needed", "battery needed",
            "a day's draw", "solar a day (albatross)", "covered", "solar a day (baseline)", "irradiance (layer)",
            "irradiance (fit)"]
    L = [_row(head), "|" + "---|" * len(head)]
    for s in W.SCENARIOS:
        i = s["id"]
        L.append(_row([s["title"]["en"]] + [f"route.{i}_{x}" for x in
                       ("night_h", "night_wh", "night_rule_wh", "night_carried", "capacity_needed_wh", "battery_needed_kg",
                        "draw_day_wh", "solar_day_albatross_wh", "day_covered", "solar_day_baseline_wh",
                        "ghi_layer_mean_w_m2", "ghi_model_mean_w_m2")]))
    return L


def table_exp(ks):
    have = {k for k, *_ in ks}
    head = ["case", "pair", "aircraft", "battery", "reason", "arrival", "closest", "soaring", "motor", "waiting",
            "motor energy", "solar", "lowest charge", "short of reserve", "short of night", "short of allowance"]
    L = [_row(head), "|" + "---|" * len(head)]
    for s in W.SCENARIOS:
        i = s["id"]
        for pair, _, _ in RT.EXP_PAIRS:
            for a in RT.AIRCRAFT:
                for cap in CAPS.values():
                    base = f"route.{i}_{pair}_{RT.SHORT[a]}_{cap}"
                    if f"{base}_reason" not in have:
                        continue
                    L.append(_row([i, f"{pair} (route.{i}_{pair}_dist_km)", RT.SHORT[a], cap]
                                  + [f"{base}_{f}" for f, _ in FIELDS]))
    return L


