"""Record keys and key tables of the route planner (docs/02-form.md#route-planning).

python -m sim.route_keys   rewrites the block of record/values.yaml between its two marker comments with the keys
below, read from sim/route.py, the solar layers in sim/viewer/route, the case files in sim/viewer/world and the
experiments in sim/out/route.json, and the key tables of docs/02-form.md#route-planning between their route_keys
markers (the prose cites the keys, never the numbers).

- the planner's settings and the battery factors of sim/route.py: assumed, open item OPEN_ITEM (the battery mass and
  the night draw also D-023);
- route.motor_share: decided, D-021;
- route.pack_cells, route.pack_fraction, route.capacity_wh, route.reserve_wh, route.sensor_day_w, route.flight_draw_w,
  route.flight_draw_rtk_w, route.panel_<a>_m2, route.takeoff_<a>_wh, route.node_step_km, route.solar_fit_w_m2 (the
  fitted irradiance per unit sine of the sun's elevation), route.solar_fit_june_kwh_m2_day (the fit's June mean at
  P51's point, against lit.insolation_50s_june_kwh_m2_day), route.solar_calls, route.solar_file_max_bytes: calculated;
- per case c: route.<c>_night_h (the astronomical night at the corridor's centre on its first day) and
  route.<c>_night_wh (that at route.night_draw_w, a lower bound of the rule), route.<c>_night_rule_wh (the planner's
  night rule at the centre: what the first run of hours below the flight draw after the start draws beyond the solar
  energy, albatross-like glider), route.<c>_night_carried (1 when the usable capacity less the reserve carries it),
  route.<c>_capacity_needed_wh and route.<c>_battery_needed_kg (the capacity and battery that would carry it with the
  reserve), route.<c>_draw_day_wh (a day of the flight draw by day and night, mean of the case's three days),
  route.<c>_solar_day_<a>_wh (the panel's daily solar energy at the centre, mean of the three days),
  route.<c>_day_covered (1 when the albatross-like glider's covers the draw), route.<c>_ghi_layer_mean_w_m2 and
  route.<c>_ghi_model_mean_w_m2 (the layer and the fitted model over the solar points and the three days),
  route.<c>_mean_wind_from_deg, route.<c>_<pair>_dist_km;
- per experiment: route.<c>_<pair>_<a>_<cap>_<field> with cap half, default or double and the fields reason (0 for a
  route, else the code of sim.route.REASONS), arrival_h (0 without a route), closest_h (the closest route's time, 0
  without one or with a route), and of the route or else the closest route soaring_h, motor_h, wait_h, motor_wh
  (with the take-offs), solar_wh, min_soc_wh, and the closest route's shortfalls against the strict rules
  reserve_short_wh, night_short_wh, allowance_short_wh (0 when it keeps the rule, or without a closest route);
- route.cmp_<nav run>_plan_ms and route.cmp_<nav run>_ratio: the leg model's speed made good (soaring first, as the
  tactical layer flies) at the conditions of each closed-loop run of docs/02-form.md#navigation, and the run's VMG over it.
"""
