"""Record keys and key tables of the wind and swell climate.

python -m sim.climate_keys   rewrites the block of record/values.yaml between the two marker comments with
the keys below, read from sim/out/climate.json, and the key tables of docs/02-form.md#wind-climate between
their climate_keys markers (the values show in the generated value table of docs/01-requirements.md; the
prose of the docs cites the keys, never the numbers).

Key names, with region r in so (Southern Ocean), np (North Pacific), home (the home operating area,
private:loc-01), season s in djf, mam, jja, son, year, threshold t in u6, dsmin (ds.min_u10_ms), skim11
(11 m/s) and best (wing.best_u10_min_ms), and aircraft a in albatross (the albatross-like glider, spells
below dsmin) and best (the best wing of the wing sizing, spells below best):

- climate.<r>_<s>_u10_{mean,p10,p50,p90}_ms and climate.<r>_<s>_below_<t>_share; climate.<r>_year_u10_std_ms
- climate.<r>_spell_<t>_{p50,p90,p99,max}_h and climate.<r>_spell_<t>_ge24h_share (share of the hours
  below t that lie in spells of at least 24 h), climate.<r>_spell_<t>_per_year_over_p99 (spells longer than
  the 99th percentile spell per point and year) and climate.<r>_spell_<t>_hw_p99_h (the 99th percentile by
  hours: 99% of the hours below t lie in spells no longer than this), for the whole year
- climate.<r>_weak_<t>_{hs2,hs3,swell2,swell3,hs_survival}_share and climate.<r>_weak_<t>_tp_s, for the
  hours below t over the whole year; climate.<r>_year_hs_survival_share for all hours
- climate.<r>_<a>_{motor,float}_{p50,p90,p99}_wh and climate.<r>_<a>_{motor,float}_p99_cell_kg (year)
- climate.<r>_<s>_<a>_{motor,float}_{p90,p99}_wh for the four seasons
- climate.solar_day_<a>_{so,home}_wh and climate.avionics_day_wh
"""
import json
import os

HERE = os.path.dirname(__file__)
ROOT = os.path.dirname(HERE)
JSON_PATH = os.path.join(HERE, "out", "climate.json")
VALUES = os.path.join(ROOT, "record", "values.yaml")
DOC = os.path.join(ROOT, "docs", "02-form.md")
BEGIN = "  # generated by python -m sim.climate_keys: begin\n"
END = "  # generated by python -m sim.climate_keys: end\n"
BASIS = "docs/02-form.md#wind-climate"
REGIONS = ("so", "np", "home")
REGION_NAME = {"so": "Southern Ocean", "np": "North Pacific", "home": "home area"}
SEASONS = ("djf", "mam", "jja", "son", "year")
THRESHOLDS = ("u6", "dsmin", "skim11", "best")
THR_NAME = {"u6": "6 m/s", "dsmin": "ds.min_u10_ms", "skim11": "11 m/s", "best": "wing.best_u10_min_ms"}
AIRCRAFT = (("albatross", "dsmin"), ("best", "best"))
AC_NAME = {"albatross": "albatross-like glider", "best": "best wing"}


def load():
    with open(JSON_PATH, encoding="utf-8") as fh:
        return json.load(fh)


def _num(x, nd):
    if x is None:
        return None
    x = round(float(x), nd)
    return int(x) if x == int(x) and nd <= 0 else x


def keys(d) -> list:
    """(key, value, unit) in a fixed order."""
    out = []
    R = d["regions"]
    for r in REGIONS:
        if r not in R:
            continue
        g = R[r]
        for s in SEASONS:
            u = g["u10"][s]
            for f in ("mean", "p10", "p50", "p90"):
                out.append((f"climate.{r}_{s}_u10_{f}_ms", _num(u[f], 2), "m/s"))
            for t in THRESHOLDS:
                out.append((f"climate.{r}_{s}_below_{t}_share", _num(g["below"][t][s], 3), "1"))
        out.append((f"climate.{r}_year_u10_std_ms", _num(g["u10"]["year"]["std"], 2), "m/s"))
        for t in THRESHOLDS:
            sp = g["spells"][t]["year"]
            for f in ("p50", "p90", "p99", "max"):
                out.append((f"climate.{r}_spell_{t}_{f}_h", _num(sp[f + "_h"], 0), "h"))
            out.append((f"climate.{r}_spell_{t}_ge24h_share", _num(sp["hours_share_in_ge24h"], 3), "1"))
            out.append((f"climate.{r}_spell_{t}_per_year_over_p99", _num(sp.get("per_year_longer_than_p99"), 2),
                        "1/year"))
            out.append((f"climate.{r}_spell_{t}_hw_p99_h", _num(sp.get("hour_weighted_p99_h"), 0), "h"))
        if g.get("weak_wind_waves"):
            out.append((f"climate.{r}_year_hs_survival_share", _num(g["waves"]["year"]["hs_ge_survival_share"], 3),
                        "1"))
            for t in THRESHOLDS:
                w = g["weak_wind_waves"][t]["year"]
                for f, src in (("hs2", "hs_ge2_share"), ("hs3", "hs_ge3_share"), ("swell2", "swell_ge2_share"),
                               ("swell3", "swell_ge3_share"), ("hs_survival", "hs_ge_survival_share")):
                    out.append((f"climate.{r}_weak_{t}_{f}_share", _num(w[src], 3), "1"))
                out.append((f"climate.{r}_weak_{t}_tp_s", _num(w["tp_p50_s_swell_ge2"], 1), "s"))
        for a, t in AIRCRAFT:
            e = g["energy"][a][t]["year"]
            for way in ("motor", "float"):
                for p in ("p50", "p90", "p99"):
                    out.append((f"climate.{r}_{a}_{way}_{p}_wh", _num(e.get(p, {}).get(way + "_wh"), 0), "Wh"))
            for way in ("motor", "float"):
                out.append((f"climate.{r}_{a}_{way}_p99_cell_kg", _num(e.get("p99", {}).get(way + "_cell_kg"), 2), "kg"))
        for s in SEASONS[:4]:
            for a, t in AIRCRAFT:
                e = g["energy"][a][t][s]
                for way in ("motor", "float"):
                    for p in ("p90", "p99"):
                        out.append((f"climate.{r}_{s}_{a}_{way}_{p}_wh", _num(e.get(p, {}).get(way + "_wh"), 0), "Wh"))
    for r in ("so", "home"):
        for a, _ in AIRCRAFT:
            out.append((f"climate.solar_day_{a}_{r}_wh", _num(d["solar_day_wh"][r][a], 1), "Wh"))
    out.append(("climate.avionics_day_wh", _num(d["avionics_day_wh"], 1), "Wh"))
    return [(k, v, u) for k, v, u in out if v is not None]


_KEYS = set()


def _k(key):
    """The key for a table cell, or "none" when the analysis had nothing to give for it."""
    return key if key in _KEYS else "none"


def basis_of(key):
    b = [BASIS]
    if key.startswith("climate.home_") or key.endswith("_home_wh"):
        b.append("private:loc-01")
    return b


def values_block(d) -> str:
    out = [BEGIN]
    for k, v, u in keys(d):
        out.append("  - key: %s\n    v: %s\n    unit: %s\n    status: calculated\n    basis:\n" % (k, v, u)
                   + "".join("      - %s\n" % b for b in basis_of(k)))
    out.append(END)
    return "".join(out)


def _row(cells):
    return "| " + " | ".join(cells) + " |"


def table_wind(d):
    head = ["region", "season", "mean", "10th", "median", "90th"] + ["below " + THR_NAME[t] for t in THRESHOLDS]
    L = [_row(head), "|" + "---|" * len(head)]
    for r in REGIONS:
        if r not in d["regions"]:
            continue
        for s in SEASONS:
            L.append(_row([REGION_NAME[r], s.upper() if s != "year" else "year"]
                          + [_k(f"climate.{r}_{s}_u10_{f}_ms") for f in ("mean", "p10", "p50", "p90")]
                          + [_k(f"climate.{r}_{s}_below_{t}_share") for t in THRESHOLDS]))
    return L


def table_spells(d):
    head = ["region", "below", "median", "90th", "99th", "longest", "share of the weak hours in spells of 24 h or more",
            "spells a year longer than the 99th", "99th by hours"]
    L = [_row(head), "|" + "---|" * len(head)]
    for r in REGIONS:
        if r not in d["regions"]:
            continue
        for t in THRESHOLDS:
            L.append(_row([REGION_NAME[r], THR_NAME[t]]
                          + [_k(f"climate.{r}_spell_{t}_{f}_h") for f in ("p50", "p90", "p99", "max")]
                          + [_k(f"climate.{r}_spell_{t}_{f}") for f in ("ge24h_share", "per_year_over_p99", "hw_p99_h")]))
    return L


def table_swell(d):
    head = ["region", "wind below", "Hs 2 m or more", "Hs 3 m or more", "swell 2 m or more", "swell 3 m or more",
            "median peak period with swell 2 m or more", "Hs at or above ds.survival_hs_m"]
    L = [_row(head), "|" + "---|" * len(head)]
    for r in REGIONS:
        g = d["regions"].get(r)
        if not g or not g.get("weak_wind_waves"):
            continue
        for t in THRESHOLDS:
            L.append(_row([REGION_NAME[r], THR_NAME[t]]
                          + [_k(f"climate.{r}_weak_{t}_{f}_share") for f in ("hs2", "hs3", "swell2", "swell3")]
                          + [_k(f"climate.{r}_weak_{t}_tp_s"), _k(f"climate.{r}_weak_{t}_hs_survival_share")]))
        L.append(_row([REGION_NAME[r], "all hours", "", "", "", "", "", _k(f"climate.{r}_year_hs_survival_share")]))
    return L


def table_energy(d):
    head = ["region", "aircraft (spells below)", "motor, median spell", "motor, 90th", "motor, 99th",
            "floating, median spell", "floating, 90th", "floating, 99th", "cells for the motor, 99th",
            "cells for floating, 99th"]
    L = [_row(head), "|" + "---|" * len(head)]
    for r in REGIONS:
        if r not in d["regions"]:
            continue
        for a, t in AIRCRAFT:
            L.append(_row([REGION_NAME[r], f"{AC_NAME[a]} ({THR_NAME[t]})"]
                          + [_k(f"climate.{r}_{a}_motor_{p}_wh") for p in ("p50", "p90", "p99")]
                          + [_k(f"climate.{r}_{a}_float_{p}_wh") for p in ("p50", "p90", "p99")]
                          + [_k(f"climate.{r}_{a}_motor_p99_cell_kg"), _k(f"climate.{r}_{a}_float_p99_cell_kg")]))
    return L


def table_battery(d):
    head = ["region", "season"]
    for a, t in AIRCRAFT:
        head += [f"{AC_NAME[a]}: {w}, {p}" for w in ("motor", "floating") for p in ("90th", "99th")]
    L = [_row(head), "|" + "---|" * len(head)]
    for r in REGIONS:
        if r not in d["regions"]:
            continue
        for s in SEASONS[:4]:
            cells = [REGION_NAME[r], s.upper()]
            for a, _ in AIRCRAFT:
                cells += [_k(f"climate.{r}_{s}_{a}_{w}_{p}_wh") for w in ("motor", "float") for p in ("p90", "p99")]
            L.append(_row(cells))
    return L


TABLES = {"wind": table_wind, "spells": table_spells, "swell": table_swell, "energy": table_energy,
          "battery": table_battery}


def replace_tables(text, d):
    _KEYS.clear()
    _KEYS.update(k for k, _, _ in keys(d))
    for name, fn in TABLES.items():
        b, e = f"<!-- climate_keys {name} begin -->\n", f"<!-- climate_keys {name} end -->"
        if b not in text:
            raise SystemExit(f"add the markers of the {name} table to docs/02-form.md first")
        i, j = text.index(b) + len(b), text.index(e)
        text = text[:i] + "\n".join(fn(d)) + "\n" + text[j:]
    return text


def main():
    d = load()
    with open(VALUES, encoding="utf-8", newline="") as fh:
        s = fh.read()
    if BEGIN not in s:
        raise SystemExit("add the two marker comment lines to record/values.yaml first")
    i, j = s.index(BEGIN), s.index(END) + len(END)
    s = s[:i] + values_block(d) + s[j:]
    with open(VALUES, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(s)
    with open(DOC, encoding="utf-8", newline="") as fh:
        t = fh.read()
    with open(DOC, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(replace_tables(t, d))


if __name__ == "__main__":
    main()
